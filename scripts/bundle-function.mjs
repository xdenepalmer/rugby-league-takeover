#!/usr/bin/env node
/**
 * Bundle an edge function + its shared.ts into ONE self-contained module.
 *
 *   node scripts/bundle-function.mjs <functionName> [outFile]
 *
 * The normal deploy path (supabase CLI / multipart Management API) uploads
 * index.ts and shared.ts as separate assets. When only the JSON function API is
 * reachable, a function must be a single file — so inline the shared helpers
 * and hoist every remaining import to the top.
 *
 * Output is byte-identical in behaviour: same code, same imports, just flattened.
 */
import fs from "node:fs";
import path from "node:path";

const name = process.argv[2];
if (!name) {
  console.error("usage: node scripts/bundle-function.mjs <functionName> [outFile]");
  process.exit(1);
}

const dir = path.join("supabase", "functions", name);
const indexSrc = fs.readFileSync(path.join(dir, "index.ts"), "utf8");
const sharedSrc = fs.readFileSync(path.join(dir, "shared.ts"), "utf8");

const IMPORT_RE = /^\s*import\s+[^;]*?from\s*['"][^'"]+['"];?\s*$/gm;

function splitImports(source) {
  const imports = [];
  const body = source.replace(IMPORT_RE, (line) => {
    // Drop the shared.ts import — its contents are inlined below.
    if (!/['"]\.\/shared\.ts['"]/.test(line)) imports.push(line.trim());
    return "";
  });
  return { imports, body };
}

const shared = splitImports(sharedSrc);
const index = splitImports(indexSrc);

// Dedupe by the exact statement so a module imported by both files appears once.
const imports = [...new Set([...shared.imports, ...index.imports])];

const out = [
  `// AUTO-GENERATED by scripts/bundle-function.mjs — do not edit.`,
  `// Source: supabase/functions/${name}/{index,shared}.ts`,
  "",
  imports.join("\n"),
  "",
  "// ── inlined shared.ts ──────────────────────────────────────────────",
  shared.body.trim(),
  "",
  `// ── ${name}/index.ts ───────────────────────────────────────────────`,
  index.body.trim(),
  "",
].join("\n");

const outFile = process.argv[3];
if (outFile) fs.writeFileSync(outFile, out);
else process.stdout.write(out);
